  function parseHexTile(hexRows, palette) {
    const canvas = document.createElement('canvas');
    canvas.width = 16;
    canvas.height = 16;
    const ctx = canvas.getContext('2d');
    const imgData = ctx.createImageData(16, 16);
    const d = imgData.data;

    for (let y = 0; y < 16; y++) {
      const row = hexRows[y] || '0000000000000000';
      for (let x = 0; x < 16; x++) {
        const idx = parseInt(row[x], 16) || 0;
        const col = palette[idx] || [0,0,0,0];
        const p = (y * 16 + x) * 4;
        d[p] = col[0];
        d[p+1] = col[1];
        d[p+2] = col[2];
        d[p+3] = col[3];
      }
    }
    ctx.putImageData(imgData, 0, 0);
    return canvas;
  }

